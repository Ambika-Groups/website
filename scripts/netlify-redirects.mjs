// Writes out/_redirects for Netlify: a 301 from every exported page's .html address to its clean
// URL (/contact.html -> /contact, /index.html -> /), so each page has one address.
// Netlify has no "any .html" pattern, so the list is generated from the export after each build.
// Netlify itself serves /contact from contact.html and 404.html for unknown paths.
import { readdir, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../out/", import.meta.url));
const SKIP = new Set(["404.html", "_not-found.html"]);

async function htmlFiles(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!entry.name.startsWith("_next") && !entry.name.startsWith("__next")) files.push(...(await htmlFiles(full)));
    } else if (entry.name.endsWith(".html")) files.push(full);
  }
  return files;
}

const rules = [];
for (const file of (await htmlFiles(OUT)).sort()) {
  const rel = relative(OUT, file).split(sep).join("/");
  if (SKIP.has(rel)) continue;
  const clean = rel === "index.html" ? "/" : `/${rel.replace(/(\/index)?\.html$/, "")}`;
  rules.push(`/${rel}  ${clean}  301!`);
}

await writeFile(join(OUT, "_redirects"), `# Generated by scripts/netlify-redirects.mjs; do not edit.\n${rules.join("\n")}\n`);
console.log(`netlify-redirects: ${rules.length} rule(s) written to out/_redirects`);
